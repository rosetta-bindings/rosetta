#!/usr/bin/env python3
"""Emit one E3 configuration: a synthetic C++ library of a chosen size, plus the
manifest that binds it.

E3 measures what the pipeline COSTS, so the library's shape is parameterised on
the four axes that can plausibly drive that cost, each controllable on its own:

    --classes C     classes in the library
    --methods M     method NAMES per class
    --fields  F     fields per class
    --overloads R   overloads per method name

which gives C*M*R methods and C*F fields, i.e. C*(F + M*R) reflected members.
Unlike E1 there are no control methods: E3 is not asking what binds, so every
member is a member and the counting stays exact.

Every type is one every backend can marshal (int, double, std::string) and every
class is default-constructible, publicly destructible and copyable, so nothing
is skipped and the emitted volume is a function of the size knobs alone.

`--targets N` takes the first N entries of TARGET_LADDER. `dynamic` is first so
that every configuration, down to the one-target one, emits the metadata tables
whose compiled size is one of the measurements.
"""
import argparse, json, os, pathlib

NS = "cost"

# Overload signatures, in declaration order. Shared in spirit with E1's list --
# every one of them is marshalable by every backend.
OVERLOAD_SIGS = [
    ("int a",                          "a"),
    ("int a, int b",                   "a + b"),
    ("double a",                       "static_cast<int>(a)"),
    ("int a, int b, int c",            "a + b + c"),
    ("const std::string &s",           "static_cast<int>(s.size())"),
    ("double a, double b",             "static_cast<int>(a + b)"),
    ("int a, double b",                "a + static_cast<int>(b)"),
    ("int a, int b, int c, int d",     "a + b + c + d"),
]

FIELD_TYPES = [("double", "0.0"), ("int", "0"), ("std::string", "{}")]

# Prefix-ordered, so --targets N is a well-defined nested set. `dynamic` leads
# because its output is measured in every configuration.
TARGET_LADDER = [
    "dynamic", "python", "node", "lua", "wasm", "julia", "nanobind",
    "csharp", "java", "typescript", "markdown", "html", "json",
    "qt", "qml", "imgui", "paraview", "rest", "openapi",
]


def emit_header(classes, methods, fields, overloads):
    if overloads > len(OVERLOAD_SIGS):
        raise SystemExit(f"--overloads max is {len(OVERLOAD_SIGS)}")

    out = [
        "// GENERATED by genlib.py -- do not edit.",
        f"// {classes} classes x {methods} names x {overloads} overloads, "
        f"{fields} fields.",
        "#pragma once",
        "#include <string>",
        "",
        f"namespace {NS} {{",
        "",
    ]
    for c in range(classes):
        cls = f"Unit{c}"
        out.append(f"    class {cls} {{")
        out.append("    public:")
        out.append(f"        {cls}() = default;")
        out.append("")
        for f in range(fields):
            ty, init = FIELD_TYPES[f % len(FIELD_TYPES)]
            out.append(f"        {ty} field{f} = {init};")
        if fields:
            out.append("")
        for n in range(methods):
            for o in range(overloads):
                params, body = OVERLOAD_SIGS[o]
                out.append(f"        int probe{n}({params}) const {{ return {body}; }}")
        out.append("    };")
        out.append("")
    out.append(f"}} // namespace {NS}")
    out.append("")
    return "\n".join(out)


def find_repo_root(start):
    here = start
    while here != here.parent and not (here / "include" / "rosetta").is_dir():
        here = here.parent
    if here == here.parent:
        raise SystemExit("could not locate the rosetta repo root above " + str(start))
    return here


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--classes",   type=int, default=16)
    ap.add_argument("--methods",   type=int, default=4)
    ap.add_argument("--fields",    type=int, default=3)
    ap.add_argument("--overloads", type=int, default=1)
    ap.add_argument("--targets",   type=int, default=3,
                    help="how many targets, taken from TARGET_LADDER")
    ap.add_argument("--out", required=True, help="config directory to fill")
    a = ap.parse_args()

    if not 1 <= a.targets <= len(TARGET_LADDER):
        raise SystemExit(f"--targets must be 1..{len(TARGET_LADDER)}")

    root = pathlib.Path(a.out).resolve()
    (root / "lib").mkdir(parents=True, exist_ok=True)
    repo = find_repo_root(root)

    (root / "lib" / "costlib.h").write_text(
        emit_header(a.classes, a.methods, a.fields, a.overloads))

    targets = TARGET_LADDER[:a.targets]
    (root / "manifest.json").write_text(json.dumps({
        "module_name": "costlib",
        "generator_name": "generator",
        "rosetta_include": os.path.relpath(repo / "include", root),
        "user_include": "lib",
        "classes": [{"name": f"{NS}::Unit{c}", "header": "costlib.h"}
                    for c in range(a.classes)],
        "targets": targets,
    }, indent=4) + "\n")

    # Ground truth, recorded beside the inputs so the analysis never re-derives
    # its baseline from the output it is measuring.
    (root / "expected.json").write_text(json.dumps({
        "classes": a.classes,
        "methods_per_class": a.methods,
        "fields_per_class": a.fields,
        "overloads": a.overloads,
        "total_methods": a.classes * a.methods * a.overloads,
        "total_fields": a.classes * a.fields,
        "total_members": a.classes * (a.fields + a.methods * a.overloads),
        "n_targets": len(targets),
        "targets": targets,
    }, indent=4) + "\n")

    print(f"{root.name}: {a.classes}c x {a.methods}m x {a.overloads}o + "
          f"{a.fields}f -> {a.classes * (a.fields + a.methods * a.overloads)} "
          f"members, {len(targets)} targets")


if __name__ == "__main__":
    main()
