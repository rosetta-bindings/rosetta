#!/usr/bin/env python3
"""Emit one version of a growing C++ library, plus the manifests for all three
arms of E2.

Versions are cumulative and deterministic: version with N classes contains
Unit0..Unit{N-1}, so a later version is a strict superset of an earlier one and
"what changed between versions" is a meaningful diff rather than a reshuffle.

Three arms, one library:

  static      one manifest listing every class -> a pybind11/N-API/sol2 binding
              per class. This is also the stand-in for the MANUAL arm: the
              emitted pybind11 module is, line for line, what a developer would
              otherwise write by hand.

  dyn         the `dynamic` backend -> auto_dynamic.{h,cpp} metadata tables.
              Stage 1 of the scriptable arm.

  meta        the `scriptable` preset -> a binding of rosetta::script itself.
              Stage 2. Note what is NOT in this manifest: any class of the
              library. That is the property E2 measures.
"""
import argparse, json, os, pathlib

NS = "evo"


def emit_header(n_classes):
    out = [
        "// GENERATED by genlib.py -- do not edit.",
        f"// {n_classes} classes.",
        "#pragma once",
        "#include <string>",
        "",
        f"namespace {NS} {{",
        "",
    ]
    for c in range(n_classes):
        k = f"Unit{c}"
        out += [
            f"    class {k} {{",
            "    public:",
            f"        {k}() = default;",
            "",
            "        double      value = 0.0;",
            "        int         index = 0;",
            "        std::string label;",
            "",
            "        double scale(double f) const { return value * f; }",
            "        int    offset(int d) const { return index + d; }",
            "        std::string describe() const { return label; }",
            "        void   reset() { value = 0.0; index = 0; }",
            "    };",
            "",
        ]
    out += [f"}} // namespace {NS}", ""]
    return "\n".join(out)


def rel_include(from_dir, repo_root):
    return os.path.relpath(repo_root / "include", from_dir)


def find_repo_root(start):
    here = start
    while here != here.parent and not (here / "include" / "rosetta").is_dir():
        here = here.parent
    if here == here.parent:
        raise SystemExit("could not locate the rosetta repo root above " + str(start))
    return here


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--classes", type=int, required=True)
    ap.add_argument("--out", required=True, help="version directory to fill")
    ap.add_argument("--static-targets", default="python,node,lua")
    ap.add_argument("--meta-targets", default="python,lua,node")
    a = ap.parse_args()

    root = pathlib.Path(a.out).resolve()
    repo = find_repo_root(root)

    for sub in ("lib", "static", "dyn", "meta"):
        (root / sub).mkdir(parents=True, exist_ok=True)

    (root / "lib" / "evolib.h").write_text(emit_header(a.classes))

    classes = [{"name": f"{NS}::Unit{c}", "header": "evolib.h"}
               for c in range(a.classes)]

    # --- arm 1: static bindings, one entry per class ---------------------
    (root / "static" / "manifest.json").write_text(json.dumps({
        "module_name": "evolib",
        "generator_name": "static_gen",
        "rosetta_include": rel_include(root / "static", repo),
        "user_include": "../lib",
        "targets": a.static_targets.split(","),
        "classes": classes,
    }, indent=4) + "\n")

    # --- arm 2 stage 1: metadata tables ----------------------------------
    (root / "dyn" / "manifest.json").write_text(json.dumps({
        "module_name": NS,
        "generator_name": "dyn_gen",
        "rosetta_include": rel_include(root / "dyn", repo),
        "user_include": "../lib",
        "targets": [{"lang": "dynamic", "name": NS}],
        "classes": classes,
    }, indent=4) + "\n")

    # --- arm 2 stage 2: the scriptable binding ---------------------------
    # Every key here is about *this project*, not about the library's contents.
    # It is byte-identical at 10 classes and at 130 -- which is the result.
    (root / "meta" / "manifest.json").write_text(json.dumps({
        "preset": "scriptable",
        "generator_name": "meta_gen",
        "rosetta_include": rel_include(root / "meta", repo),
        "user_include": ["../lib", "../dyn/bindings/dynamic"],
        "user_sources": ["../dyn/bindings/dynamic/auto_dynamic.cpp"],
        "module_init": {
            "headers": ["auto_dynamic.h"],
            "statements": [f"{NS}::register_all()"],
        },
        "targets": a.meta_targets.split(","),
    }, indent=4) + "\n")

    (root / "expected.json").write_text(json.dumps({
        "classes": a.classes,
        "fields_per_class": 3,
        "methods_per_class": 4,
        "total_fields": a.classes * 3,
        "total_methods": a.classes * 4,
    }, indent=4) + "\n")

    print(f"{root.name}: {a.classes} classes "
          f"({a.classes*3} fields, {a.classes*4} methods)")


if __name__ == "__main__":
    main()
