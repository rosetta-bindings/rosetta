#!/usr/bin/env python3
"""Emit the benchmark library for E4 plus the manifests for each arm.

The library is small on purpose: E4 measures per-call cost, not scale, so one
class with a representative spread of operations is enough. Each operation is
chosen to isolate one cost:

  ping        trivial call        -- pure dispatch, no marshalling
  value       field get/set       -- the cheapest possible member access
  combine     3 scalar arguments  -- argument marshalling
  clone       returns an object   -- return-value boxing and ownership
  scale_all   vector<double>      -- bulk data across the boundary
  at          3-candidate overload set -- overload scoring at call time

`at` exists so the cost of the overload *resolution* that E1 showed to be
valuable can be priced here. That is the point of running E4 after E1: E1 says
late binding buys expressiveness, E4 says what it costs.
"""
import argparse, json, os, pathlib

NS = "bench"

HEADER = r"""// GENERATED by genlib.py -- do not edit.
#pragma once
#include <string>
#include <vector>

namespace bench {

    class Widget {
    public:
        Widget() = default;

        double value = 1.5;
        int    index = 7;

        // trivial call: no arguments, no marshalling beyond the return
        int ping() const { return 1; }

        // three scalar arguments
        double combine(double a, double b, int c) const { return a * b + c; }

        // returns an object by value
        Widget clone() const { return *this; }

        // bulk data both ways
        std::vector<double> scale_all(const std::vector<double> &v, double f) const {
            std::vector<double> out;
            out.reserve(v.size());
            for (double x : v) out.push_back(x * f);
            return out;
        }

        // a 3-candidate overload set, to price overload scoring
        int at(int i) const { return i; }
        int at(int i, int j) const { return i + j; }
        int at(double x) const { return static_cast<int>(x); }
    };

} // namespace bench
"""


def rel_include(from_dir, repo_root):
    return os.path.relpath(repo_root / "include", from_dir)


def find_repo_root(start):
    here = start
    while here != here.parent and not (here / "include" / "rosetta").is_dir():
        here = here.parent
    if here == here.parent:
        raise SystemExit("could not locate the rosetta repo root above " + str(start))
    return here


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    root = pathlib.Path(a.out).resolve()
    repo = find_repo_root(root)
    for sub in ("lib", "dyn", "static", "meta"):
        (root / sub).mkdir(parents=True, exist_ok=True)

    (root / "lib" / "benchlib.h").write_text(HEADER)
    classes = [{"name": f"{NS}::Widget", "header": "benchlib.h"}]

    # metadata tables -- the dynamic arm, and stage 1 of the scriptable arm
    (root / "dyn" / "manifest.json").write_text(json.dumps({
        "module_name": NS,
        "generator_name": "dyn_gen",
        "rosetta_include": rel_include(root / "dyn", repo),
        "user_include": "../lib",
        "targets": [{"lang": "dynamic", "name": NS}],
        "classes": classes,
    }, indent=4) + "\n")

    # the generated pybind11 module -- what a developer would hand-write
    (root / "static" / "manifest.json").write_text(json.dumps({
        "module_name": "benchstatic",
        "generator_name": "static_gen",
        "rosetta_include": rel_include(root / "static", repo),
        "user_include": "../lib",
        "targets": [{"lang": "python", "name": "benchstatic"}],
        "classes": classes,
    }, indent=4) + "\n")

    # the scriptable binding: rosetta::script exposed to Python, naming no
    # class of this library
    (root / "meta" / "manifest.json").write_text(json.dumps({
        "preset": "scriptable",
        "generator_name": "meta_gen",
        "rosetta_include": rel_include(root / "meta", repo),
        "user_include": ["../lib", "../dyn/bindings/dynamic"],
        "user_sources": ["../dyn/bindings/dynamic/auto_dynamic.cpp"],
        "module_init": {
            "headers": ["auto_dynamic.h"],
            "statements": [f"{NS}::register_all()"],
        },
        "targets": [{"lang": "python", "name": "benchmeta"}],
    }, indent=4) + "\n")

    print(f"{root.name}: benchmark library + 3 arm manifests")


if __name__ == "__main__":
    main()
