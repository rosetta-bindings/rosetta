#!/usr/bin/env python3
"""Emit a synthetic C++ library with a controlled overload structure, plus the
rosetta manifest that binds it.

The library is deliberately boring: every parameter and return type is one that
*every* backend can marshal (int, double, std::string), every class is default
constructible, publicly destructible and copyable. That is the point — the only
thing that should cause a member to be dropped is the overload policy under
test. Anything else showing up in coverage.json is a confound, and the analysis
reports it separately rather than folding it in.

Shape, for --classes C --names N --overloads R:

    C classes x N method names x R overloads each  = C*N*R methods
    plus C*N non-overloaded "control" methods      (one per name, never dropped)
    plus 2 fields per class                        (never dropped)

A first-only target can bind at most C*N of the C*N*R overloaded methods, so the
predicted static loss is C*N*(R-1) and is linear in R. A late-bound target keeps
all C*N*R. That divergence is what E1 measures.
"""
import argparse, json, pathlib, textwrap

# Signatures used to build an overload set, in declaration order. Index 0 is
# the one a first-only target keeps ("first" means first-declared).
OVERLOAD_SIGS = [
    ("int a",                                    "a"),
    ("int a, int b",                             "a + b"),
    ("double a",                                 "static_cast<int>(a)"),
    ("int a, int b, int c",                      "a + b + c"),
    ("const std::string &s",                     "static_cast<int>(s.size())"),
    ("double a, double b",                       "static_cast<int>(a + b)"),
    ("int a, double b",                          "a + static_cast<int>(b)"),
    ("int a, int b, int c, int d",               "a + b + c + d"),
]


def emit_header(classes, names, overloads, ns="ol"):
    if overloads > len(OVERLOAD_SIGS):
        raise SystemExit(f"--overloads max is {len(OVERLOAD_SIGS)}")

    out = [
        "// GENERATED by genlib.py -- do not edit.",
        f"// {classes} classes x {names} names x {overloads} overloads.",
        "#pragma once",
        "#include <string>",
        "",
        f"namespace {ns} {{",
        "",
    ]
    for c in range(classes):
        cls = f"Unit{c}"
        out.append(f"    class {cls} {{")
        out.append("    public:")
        out.append(f"        {cls}() = default;")
        out.append("")
        out.append("        double scale = 1.0;")
        out.append("        int    count = 0;")
        out.append("")
        for n in range(names):
            nm = f"probe{n}"
            # the overload set under test
            for o in range(overloads):
                params, body = OVERLOAD_SIGS[o]
                out.append(f"        int {nm}({params}) const {{ return {body}; }}")
            # a control method with a unique name: never part of an overload
            # set, so it must bind everywhere. Its count is the baseline that
            # separates "dropped by overload policy" from "dropped for some
            # other reason".
            out.append(f"        int solo{n}(int a) const {{ return a; }}")
            out.append("")
        out.append("    };")
        out.append("")
    out.append(f"}} // namespace {ns}")
    out.append("")
    return "\n".join(out)


def emit_manifest(classes, targets, rosetta_include, ns="ol"):
    # Both paths are resolved by rosetta_gen relative to the MANIFEST's own
    # directory, so "lib" (not "../lib") is the sibling library folder.
    return {
        "module_name": "overloadlib",
        "generator_name": "generator",
        "rosetta_include": rosetta_include,
        "user_include": "lib",
        "classes": [{"name": f"{ns}::Unit{c}", "header": "overloadlib.h"}
                    for c in range(classes)],
        "targets": list(targets),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--classes",   type=int, default=8)
    ap.add_argument("--names",     type=int, default=6)
    ap.add_argument("--overloads", type=int, default=3)
    ap.add_argument("--out",       required=True, help="config directory to fill")
    ap.add_argument("--rosetta-include", default=None,
                    help="default: computed relative to the repo root")
    ap.add_argument("--targets", default="python,nanobind,julia,lua,node,wasm,csharp,java,typescript,dynamic")
    a = ap.parse_args()

    root = pathlib.Path(a.out).resolve()
    (root / "lib").mkdir(parents=True, exist_ok=True)

    # Walk up to the repo root so a config directory at any depth gets a correct
    # relative path to <repo>/include.
    if a.rosetta_include:
        rosetta_include = a.rosetta_include
    else:
        here = root
        while here != here.parent and not (here / "include" / "rosetta").is_dir():
            here = here.parent
        if here == here.parent:
            raise SystemExit("could not locate the rosetta repo root above " + str(root))
        import os
        rosetta_include = os.path.relpath(here / "include", root)

    (root / "lib" / "overloadlib.h").write_text(
        emit_header(a.classes, a.names, a.overloads))

    manifest = emit_manifest(a.classes, a.targets.split(","), rosetta_include)
    (root / "manifest.json").write_text(json.dumps(manifest, indent=4) + "\n")

    # The ground truth, recorded next to the inputs so the analysis never has to
    # re-derive it from the generator's own output.
    (root / "expected.json").write_text(json.dumps({
        "classes": a.classes,
        "names": a.names,
        "overloads": a.overloads,
        "overloaded_methods": a.classes * a.names * a.overloads,
        "control_methods":    a.classes * a.names,
        "total_methods":      a.classes * a.names * (a.overloads + 1),
        "fields":             a.classes * 2,
        # what a first-only target can keep: one per overload set, plus every control
        "predicted_first_only_methods": a.classes * a.names * 2,
        "predicted_overload_drops":     a.classes * a.names * (a.overloads - 1),
    }, indent=4) + "\n")

    print(f"{root}: {a.classes}c x {a.names}n x {a.overloads}o "
          f"= {a.classes*a.names*(a.overloads+1)} methods")


if __name__ == "__main__":
    main()
